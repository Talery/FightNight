import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const outfile = resolve(root, 'supabase/functions/verify-daily/_shared/daily-protocol.js')
const checkOnly = process.argv.includes('--check')

const result = await build({
  entryPoints: [resolve(root, 'src/game/daily-protocol.ts')],
  outfile,
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  treeShaking: true,
  legalComments: 'none',
  banner: { js: '// Generated by npm run build:functions. Do not edit by hand.' },
  write: false,
})

const generated = Buffer.from(result.outputFiles[0].contents)
if (checkOnly) {
  const current = await readFile(outfile).catch(() => null)
  if (!current?.equals(generated)) throw new Error('verify-daily replay bundle is stale; run npm run build:functions')
  console.log('verify-daily replay bundle is current')
} else {
  await mkdir(dirname(outfile), { recursive: true })
  await writeFile(outfile, generated)
  console.log(`Built ${outfile}`)
}
